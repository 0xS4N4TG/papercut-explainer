# Write src/scenes/index.ts from episode.json ("scenes" + "banners") and a stub file for every scene that doesn't exist yet.
#   usage (from a project dir): python3 $PAPERCUT_LIB/papercut/stubs.py
import json, os
EP = json.load(open("episode.json")); ids = [s[0] for s in EP["scenes"]]; B = EP.get("banners", {})
imp = "\n".join(f"import {{{i}}} from './{i}';" for i in ids)
rows = "\n".join(f"  {{id: '{i}', component: {i}, banner: {json.dumps(B.get(i, ''), ensure_ascii=False)}, band: 0.745}}," for i in ids)
open("src/scenes/index.ts", "w").write(f"""// Scene registry (generated by papercut/stubs.py from episode.json): id → component, banner (fact track), caption band.
import React from 'react';
{imp}

export type SceneDef = {{id: string; component: React.FC; banner: string; band: number}};
export const SCENES: SceneDef[] = [
{rows}
];
""")
made = 0
for i in ids:
    p = f"src/scenes/{i}.tsx"
    if os.path.exists(p): continue
    open(p, "w").write(f"""// {i}: STUB, replaced by its scene agent (see STORYBOARD.md).
import React from 'react';
import {{AbsoluteFill}} from 'remotion';
import {{Room}} from '../lib/paper/sets';

export const {i}: React.FC = () => (
  <AbsoluteFill>
    <Room color="grey" />
  </AbsoluteFill>
);
"""); made += 1
print(len(ids), "scenes in index.ts,", made, "new stubs")
